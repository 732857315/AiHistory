const fn release_year(year: u16, month: usize, day: u16) -> f64 {
    let leap = year.is_multiple_of(4) && (!year.is_multiple_of(100) || year.is_multiple_of(400));
    let lengths = [
        31_u16,
        if leap { 29 } else { 28 },
        31,
        30,
        31,
        30,
        31,
        31,
        30,
        31,
        30,
        31,
    ];
    let mut preceding = day - 1;
    let mut i = 0;
    while i + 1 < month {
        preceding += lengths[i];
        i += 1;
    }
    year as f64 + preceding as f64 / if leap { 366.0 } else { 365.0 }
}

